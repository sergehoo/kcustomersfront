def curtain(name, width, top, bottom, centre_x, z, axis='x', folds=7, depth=.05):
    """A pleated sheer panel: a dense grid so the runtime breeze can move it."""
    bm = bmesh.new()
    cols, rows = folds * 6, 12
    height = top - bottom
    grid = []
    for r in range(rows + 1):
        row = []
        for c in range(cols + 1):
            u = c / cols - .5
            v = r / rows
            wave = math.sin(c / cols * folds * 2 * math.pi) * depth / 2
            if axis == 'x':
                p = B(centre_x + u * width, bottom + v * height, z + wave)
            else:
                p = B(centre_x + wave, bottom + v * height, z + u * width)
            row.append(bm.verts.new(p))
        grid.append(row)
    for r in range(rows):
        for c in range(cols):
            bm.faces.new((grid[r][c], grid[r][c + 1], grid[r + 1][c + 1], grid[r + 1][c]))
    me = bpy.data.meshes.new(name)
    bm.to_mesh(me)
    bm.free()
    uv = me.uv_layers.new()
    for poly in me.polygons:
        poly.use_smooth = True
        for li in poly.loop_indices:
            index = me.loops[li].vertex_index
            uv.data[li].uv = ((index % (cols + 1)) / cols, (index // (cols + 1)) / rows)
    obj = bpy.data.objects.new(name, me)
    obj.data.materials.append(SHEER)
    COLL.objects.link(obj)
    REPORT.append(name)
    return obj


