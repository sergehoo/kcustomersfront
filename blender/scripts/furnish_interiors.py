def sofa(name, length, depth, position, facing, fabric, base_mat, outdoor=False):
    L, D = length, depth
    parts = [
        part((L - .12, .10, D - .12), (0, .05, 0), base_mat, bevel=.01),
        part((L, .22, D), (0, .21, 0), fabric, bevel=.05, segments=3),
        part((L, .44, .22), (0, .53, -D / 2 + .11), fabric, bevel=.06, segments=3),
    ]
    for side in (-1, 1):
        parts.append(part((.2, .36, D), (side * (L / 2 - .1), .42, 0), fabric, bevel=.06, segments=3))
    seats = 3 if L > 2.2 else 2
    width = (L - .4) / seats
    for i in range(seats):
        x = -L / 2 + .2 + width * (i + .5)
        parts.append(part((width - .02, .14, D - .3), (x, .39, .1), fabric, bevel=.05, segments=3, sub=1))
        parts.append(part((width - .04, .4, .18), (x, .62, -D / 2 + .3), fabric, bevel=.07, segments=3, sub=1, tilt=-10))
    if not outdoor:
        for x, mat, tilt in ((-L / 2 + .45, CUSHION_SAND, -12), (-L / 2 + .78, CUSHION_TERRA, -8), (L / 2 - .5, CUSHION_CHARCOAL, -12)):
            parts.append(part((.46, .44, .14), (x, .66, -D / 2 + .42), mat, bevel=.08, segments=3, sub=1, tilt=tilt))
        parts.append(part((.5, .03, D - .1), (L / 2 - .12, .62, .02), THROW, bevel=.012))
        parts.append(part((.06, .32, D - .1), (L / 2 + .01, .48, .02), THROW, bevel=.012))
    else:
        for x in (-L / 2 + .5, L / 2 - .5):
            parts.append(part((.44, .42, .14), (x, .66, -D / 2 + .42), CUSHION_SAND, bevel=.08, segments=3, sub=1, tilt=-12))
    return assemble(name, parts, position, facing)


