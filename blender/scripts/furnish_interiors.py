def open_terrace_door():
    """Slides one leaf of the living room's south bay open, so the visit walks
    out to the terrace through a real opening: the glass between two cuts is
    removed and the leaf is parked in front of the fixed pane beside it."""
    name = 'Cube.001_Glass_0'
    obj = bpy.data.objects.get(name)
    if obj is None:
        return
    if obj.data.users > 1:
        obj.data = obj.data.copy()
    x0, x1 = -.95, .36
    bm = bmesh.new()
    bm.from_mesh(obj.data)
    world = obj.matrix_world
    inverse = world.inverted()
    for x in (x0, x1):
        bmesh.ops.bisect_plane(bm, geom=bm.verts[:] + bm.edges[:] + bm.faces[:],
                               plane_co=inverse @ B(x, 0, 0), plane_no=(world.to_3x3().transposed() @ Vector((1, 0, 0))).normalized())
    doomed = []
    for face in bm.faces:
        c = world @ face.calc_center_median()
        if x0 < c.x < x1 and 8.3 < -c.y < 8.9:
            doomed.append(face)
    bmesh.ops.delete(bm, geom=doomed, context='FACES')
    bm.to_mesh(obj.data)
    bm.free()
    obj.data.update()
    glass = obj.material_slots[0].material if obj.material_slots else None
    width = x1 - x0
    leaf = [part((width, CEIL0 - F0 - .06, .012), (0, (CEIL0 - F0) / 2, 0), glass or SHEER)]
    for side in (-1, 1):
        leaf.append(part((.04, CEIL0 - F0 - .04, .04), (side * width / 2, (CEIL0 - F0) / 2, 0), BLACKMETAL))
    assemble('Living_SlidingDoor_Leaf', leaf, (x0 - width / 2 + .02, F0, 8.7))
    REPORT.append(f'terrace door: {len(doomed)} glass faces removed')


def soften_existing():
    """Applies the upper floor's bevel/subdivision modifiers the glTF export
    ignored (export_apply=False), so its soft goods are actually soft."""
    count = 0
    for name in ('MASTER_SUITE', 'MASTER_BATHROOM', 'DRESSING', 'SECOND_BEDROOM'):
        coll = bpy.data.collections.get(name)
        if not coll:
            continue
        for obj in coll.objects:
            if obj.type == 'MESH' and obj.modifiers:
                apply_modifiers(obj)
                count += 1
    REPORT.append(f'softened {count} objects')


