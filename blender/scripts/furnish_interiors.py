# ── helpers ──────────────────────────────────────────────────────────────────
def collection(name):
    coll = bpy.data.collections.get(name)
    if coll:
        for obj in list(coll.objects):
            bpy.data.objects.remove(obj, do_unlink=True)
    else:
        coll = bpy.data.collections.new(name)
        bpy.context.scene.collection.children.link(coll)
    return coll


def put(obj):
    for c in list(obj.users_collection):
        c.objects.unlink(obj)
    COLL.objects.link(obj)


def select_only(objects, active):
    """Operators act on the real selection, whatever the context override says:
    after a chain of scripts, stale selections moved unrelated objects."""
    layer = bpy.context.view_layer
    layer.update()
    for obj in bpy.data.objects:
        if obj.name in layer.objects:
            obj.select_set(False)
    for obj in objects:
        obj.select_set(True)
    layer.objects.active = active


def apply_modifiers(obj):
    if not obj.modifiers:
        return
    if obj.data.users > 1:
        obj.data = obj.data.copy()
    with bpy.context.temp_override(object=obj, active_object=obj, selected_objects=[obj], selected_editable_objects=[obj]):
        for mod in list(obj.modifiers):
            bpy.ops.object.modifier_apply(modifier=mod.name)


def part(size, centre, mat, bevel=0.0, segments=2, sub=0, tilt=0.0):
    """A box in glTF-local axes (sx along x, sy up, sz along z), rounded by a
    real (applied) bevel and optional subdivision. `tilt` leans it back about x."""
    bpy.ops.mesh.primitive_cube_add(size=1, location=B(*centre))
    obj = bpy.context.object
    obj.scale = (size[0], size[2], size[1])
    if tilt:
        obj.rotation_euler = (math.radians(tilt), 0, 0)
    bpy.ops.object.transform_apply(location=False, rotation=bool(tilt), scale=True)
    if bevel:
        mod = obj.modifiers.new('bevel', 'BEVEL')
        mod.width = bevel
        mod.segments = segments
        mod.limit_method = 'ANGLE'
    if sub:
        mod = obj.modifiers.new('sub', 'SUBSURF')
        mod.levels = sub
        mod.render_levels = sub
    apply_modifiers(obj)
    obj.data.materials.append(mat)
    bpy.ops.object.shade_smooth() if sub else None
    return obj


def cyl(radius, height, centre, mat, vertices=32, bevel=0.0):
    bpy.ops.mesh.primitive_cylinder_add(radius=radius, depth=height, vertices=vertices, location=B(*centre))
    obj = bpy.context.object
    if bevel:
        mod = obj.modifiers.new('bevel', 'BEVEL')
        mod.width = bevel
        mod.segments = 2
        mod.limit_method = 'ANGLE'
        apply_modifiers(obj)
    bpy.ops.object.shade_smooth()
    obj.data.materials.append(mat)
    return obj


def cone(r1, r2, height, centre, mat, vertices=32):
    bpy.ops.mesh.primitive_cone_add(radius1=r1, radius2=r2, depth=height, vertices=vertices, location=B(*centre))
    obj = bpy.context.object
    bpy.ops.object.shade_smooth()
    obj.data.materials.append(mat)
    return obj


def yaw_for(facing):
    """Blender Z rotation that turns a model's front (glTF +z) towards `facing`
    (dx, dz) in glTF."""
    return math.atan2(-facing[1], facing[0]) + math.pi / 2


def assemble(name, parts, position, facing=(0, 1)):
    """Joins parts built around the origin (front towards glTF +z) into one
    object, then turns and places it."""
    select_only(parts, parts[0])
    with bpy.context.temp_override(active_object=parts[0], selected_editable_objects=parts, selected_objects=parts):
        # Every part's origin to the world origin first, so the joined
        # object's origin is the piece's own origin (its base centre).
        bpy.ops.object.transform_apply(location=True, rotation=False, scale=False)
        if len(parts) > 1:
            bpy.ops.object.join()
    obj = parts[0]
    obj.name = name
    obj.rotation_euler = (0, 0, yaw_for(facing))
    obj.location = B(*position)
    put(obj)
    REPORT.append(name)
    return obj


def import_ph(asset, name, position, facing=(0, 1), scale=1.0, source=None):
    """Imports a Poly Haven glTF (or duplicates an earlier import), joined into
    one object, standing on `position` (its base centre)."""
    if source is not None:
        obj = source.copy()
        obj.name = name
        COLL.objects.link(obj)
    else:
        before = set(bpy.data.objects)
        bpy.ops.import_scene.gltf(filepath=os.path.join(PH, asset, f'{asset}_1k.gltf'))
        new = [o for o in bpy.data.objects if o not in before]
        names = [o.name for o in new]
        meshes = [o for o in new if o.type == 'MESH']
        for o in meshes:
            world = o.matrix_world.copy()
            o.parent = None
            o.matrix_world = world
        select_only(meshes, meshes[0])
        with bpy.context.temp_override(active_object=meshes[0], selected_editable_objects=meshes, selected_objects=meshes):
            bpy.ops.object.transform_apply(location=True, rotation=True, scale=True)
            if len(meshes) > 1:
                bpy.ops.object.join()
        obj = meshes[0]
        keep = obj.name
        for leftover in names:
            if leftover != keep and leftover in bpy.data.objects:
                bpy.data.objects.remove(bpy.data.objects[leftover], do_unlink=True)
        obj.name = name
        # Base centre to the origin, so `position` is where it stands.
        cs = [Vector(c) for c in obj.bound_box]
        lo = Vector((min(c.x for c in cs), min(c.y for c in cs), min(c.z for c in cs)))
        hi = Vector((max(c.x for c in cs), max(c.y for c in cs), max(c.z for c in cs)))
        shift = Vector(((lo.x + hi.x) / 2, (lo.y + hi.y) / 2, lo.z))
        obj.data.transform(__import__('mathutils').Matrix.Translation(-shift))
        put(obj)
    obj.scale = (scale, scale, scale)
    obj.rotation_euler = (0, 0, yaw_for(facing))
    obj.location = B(*position)
    select_only([], None)
    REPORT.append(name)
    return obj


def surface(x, z, above):
    """Height of the first surface under (x, above, z)."""
    dg = bpy.context.evaluated_depsgraph_get()
    ok, loc, *_ = bpy.context.scene.ray_cast(dg, B(x, above, z), Vector((0, 0, -1)))
    return loc.z if ok else None


def wall(x, y, z, direction):
    dg = bpy.context.evaluated_depsgraph_get()
    d = Vector((direction[0], -direction[2], direction[1]))
    ok, loc, *_ = bpy.context.scene.ray_cast(dg, B(x, y, z), d)
    return Vector((loc.x, loc.z, -loc.y)) if ok else None


def canvas(name, art, width, height, centre, facing, depth=.035):
    """A gallery-wrapped canvas: painted face, linen-coloured edges."""
    face = part((width, height, .004), (0, 0, depth / 2), art_material(f'ART_{art.upper()}', f'art_{art}.png'))
    # Planar UVs over the painted face.
    me = face.data
    uv = me.uv_layers.active or me.uv_layers.new()
    for poly in me.polygons:
        for li in poly.loop_indices:
            co = me.vertices[me.loops[li].vertex_index].co
            uv.data[li].uv = (co.x / width + .5, co.z / height + .5)
    body = part((width, height, depth), (0, 0, 0), LINEN_WARM, bevel=.004)
    return assemble(name, [face, body], centre, facing)


def remove_prefix(prefix):
    for obj in list(bpy.data.objects):
        if obj.name.startswith(prefix):
            name = obj.name
            bpy.data.objects.remove(obj, do_unlink=True)
            REPORT.append(f'removed {name}')


def clone_group(prefix, name, x, z, lift=0.0):
    """Linked copies of every object of a multi-part asset (pot, soil, leaves),
    moved together so the group's centre lands on (x, z)."""
    sources = [o for o in bpy.data.objects if o.name.startswith(prefix) and o.type == 'MESH' and o.users_collection and o.users_collection[0] != COLL]
    if not sources:
        return
    cx = sum(o.matrix_world.translation.x for o in sources) / len(sources)
    cy = sum(o.matrix_world.translation.y for o in sources) / len(sources)
    target = B(x, 0, z)
    for i, src in enumerate(sources):
        copy = src.copy()
        copy.name = f'{name}_{i}'
        copy.parent = None
        copy.matrix_world = src.matrix_world.copy()
        copy.location = copy.matrix_world.translation + Vector((target.x - cx, target.y - cy, lift))
        COLL.objects.link(copy)
    REPORT.append(name)


