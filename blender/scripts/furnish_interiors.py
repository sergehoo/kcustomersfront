def material(name, base, roughness, metallic=0.0, sheen=0.0, normal_from=None, scale=1.0, emission=None, strength=0.0):
    mat = bpy.data.materials.get(name)
    if mat:
        return mat
    mat = bpy.data.materials.new(name)
    mat.use_nodes = True
    nodes, links = mat.node_tree.nodes, mat.node_tree.links
    bsdf = nodes['Principled BSDF']
    bsdf.inputs['Base Color'].default_value = (*base, 1)
    bsdf.inputs['Roughness'].default_value = roughness
    bsdf.inputs['Metallic'].default_value = metallic
    if 'Sheen Weight' in bsdf.inputs:
        bsdf.inputs['Sheen Weight'].default_value = sheen
    if emission is not None:
        bsdf.inputs['Emission Color'].default_value = (*emission, 1)
        bsdf.inputs['Emission Strength'].default_value = strength
    if normal_from:
        path = os.path.join(TEX, normal_from, 'normal.webp')
        if os.path.exists(path):
            coords = nodes.new('ShaderNodeTexCoord')
            mapping = nodes.new('ShaderNodeMapping')
            mapping.inputs['Scale'].default_value = (scale, scale, scale)
            tex = nodes.new('ShaderNodeTexImage')
            tex.image = bpy.data.images.load(path, check_existing=True)
            tex.image.colorspace_settings.name = 'Non-Color'
            nmap = nodes.new('ShaderNodeNormalMap')
            nmap.inputs['Strength'].default_value = .7
            links.new(coords.outputs['UV'], mapping.inputs['Vector'])
            links.new(mapping.outputs['Vector'], tex.inputs['Vector'])
            links.new(tex.outputs['Color'], nmap.inputs['Color'])
            links.new(nmap.outputs['Normal'], bsdf.inputs['Normal'])
    return mat


def art_material(name, filename):
    mat = bpy.data.materials.get(name)
    if mat:
        return mat
    mat = material(name, (1, 1, 1), .82)
    nodes, links = mat.node_tree.nodes, mat.node_tree.links
    tex = nodes.new('ShaderNodeTexImage')
    tex.image = bpy.data.images.load(os.path.join(ART, filename), check_existing=True)
    tex.image.pack()
    links.new(tex.outputs['Color'], nodes['Principled BSDF'].inputs['Base Color'])
    return mat


