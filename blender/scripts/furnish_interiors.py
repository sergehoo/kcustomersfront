def rename():
    """Readable names for the pieces the camera frames, and every mesh named
    like its object — three.js names multi-material parts after the mesh."""
    for obj in list(bpy.data.objects):
        for old, new in RENAMES.items():
            if obj.name.startswith(old):
                obj.name = new + obj.name[len(old):]
                break
        if obj.name.startswith('modern_arm_chair'):
            obj.name = 'Master_Armchair_' + obj.name[len('modern_arm_chair'):].lstrip('_')
    for obj in COLL.objects:
        if obj.type == 'MESH' and obj.data.users == 1:
            obj.data.name = obj.name
    for name in ('MASTER_SUITE', 'MASTER_BATHROOM', 'DRESSING', 'SECOND_BEDROOM'):
        coll = bpy.data.collections.get(name)
        for obj in (coll.objects if coll else []):
            if obj.type == 'MESH' and obj.data.users == 1:
                obj.data.name = obj.name


